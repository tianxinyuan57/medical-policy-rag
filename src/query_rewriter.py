# 疑问词/语气词：改写时无需保留，避免污染 BM25
STOP_PATTERNS = re.compile(
    r'(怎么办|怎么样|怎么|如何|是什么|有哪些|哪些|多少|吗|呢|啊|的话|一下|请问)'
)


def rewrite_by_dict(query: str) -> tuple[str, list[tuple[str, list[str]]]]:
    """基于领域词表做扩展式改写（零 LLM 成本）。

    Args:
        query: 用户原始问题

    Returns:
        (改写后的查询, [(命中的口语词, 扩展出的术语), …])
    """
    hits: list[tuple[str, list[str]]] = []
    added: list[str] = []

    # 长词优先匹配，避免「异地看病」被「看病」抢先
    for spoken in sorted(TERM_MAP, key=len, reverse=True):
        if spoken not in query:
            continue
        terms = TERM_MAP[spoken]
        # 已经在原问题里出现的术语不重复添加
        new_terms = [t for t in terms if t not in query and t not in added]
        if new_terms:
            hits.append((spoken, new_terms))
            added.extend(new_terms)

    if not added:
        return query, []

    # 扩展式：原问题 + 术语（保留原问题给向量检索，术语喂给 BM25）
    return f"{query} {' '.join(added)}", hits


def rewrite_by_llm(query: str) -> tuple[str, str]:
    """用 LLM 补充专业术语（处理词表覆盖不到的长尾表达）。

    Returns:
        (改写后的查询, LLM 给出的术语串)
    """
    from llm import ask_llm

    system = """你是医疗保障政策领域的检索专家。
用户会用口语提问，你的任务是补充对应的**法规专业术语**，用于关键词检索。

要求：
1. 只输出术语，用空格分隔，不要解释、不要标点
2. 最多输出 5 个术语
3. 术语要贴近中国医疗卫生/医保法规的正式用词
4. 如果问题已经很专业、无需补充，输出「无」

示例：
问题：异地看病能报多少钱
输出：跨省异地就医 直接结算 支付比例 基本医疗保险

问题：医疗机构麻醉药品管理规定
输出：无"""

    try:
        result = ask_llm(system, f"问题：{query}\n输出：").strip()
    except Exception:
        return query, ""

    if not result or result.startswith("无"):
        return query, ""

    # 清洗：只保留中文/字母/数字和空格
    terms = re.sub(r'[^一-龥A-Za-z0-9\s]', ' ', result)
    terms = ' '.join(t for t in terms.split() if len(t) > 1)[:120]

    if not terms:
        return query, ""
    return f"{query} {terms}", terms


def rewrite(query: str, use_llm: bool = False) -> dict:
    """查询改写主入口。

    Args:
        query: 原始问题
        use_llm: 词表未命中时是否调用 LLM 兜底

    Returns:
        {
          "original":   原始问题,
          "rewritten":  改写后用于检索的查询,
          "dict_hits":  词表命中明细,
          "llm_terms":  LLM 补充的术语,
          "changed":    是否发生了改写,
        }
    """
    rewritten, hits = rewrite_by_dict(query)
    llm_terms = ""

    # 词表没命中且开启了 LLM 兜底
    if not hits and use_llm:
        rewritten, llm_terms = rewrite_by_llm(query)

    return {
        "original": query,
        "rewritten": rewritten,
        "dict_hits": hits,
        "llm_terms": llm_terms,
        "changed": rewritten != query,
    }


