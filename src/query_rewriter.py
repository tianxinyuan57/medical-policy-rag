"""查询改写（Query Rewriting）—— 弥合「用户说人话」与「法规说术语」的鸿沟

====================================================================
问题：用户的词和法规的词不是一套
====================================================================

对知识库做词频统计后发现的真实差距：

    用户会说              法规实际用词            知识库出现次数
    ────────────────────────────────────────────────────────
    报销比例        →     支付比例                2 vs 18
    异地看病        →     跨省异地就医            0 vs 299
    医保定点药店     →     定点医药机构           0 vs 345
    突击检查        →     飞行检查                0 vs 76

「报销比例」在 94 部法规里只出现 2 次，而「支付比例」出现 18 次。
用户按自己的说法提问，BM25 关键词路几乎必然落空。

====================================================================
解法：扩展式改写，而非替换式
====================================================================

    ✗ 替换：「异地看病能报销吗」→「跨省异地就医能支付吗」
      风险：丢失用户原意，向量检索反而变差

    ✓ 扩展：「异地看病能报销吗 跨省异地就医 直接结算 支付比例」
      好处：BM25 命中术语，向量检索保留原始语义

因为本项目用的是 BM25 + 向量的混合检索，扩展式改写能让
两路各取所需，互不干扰。

====================================================================
两级改写策略
====================================================================

1. **词表改写（零成本，默认开启）**
   基于领域词典做字符串匹配，无 LLM 调用，延迟 ~0ms。
   覆盖高频口语表达。

2. **LLM 改写（可选，处理长尾）**
   词表覆盖不到的表达，交给 LLM 补充术语。
   有成本和延迟，默认关闭。
"""

